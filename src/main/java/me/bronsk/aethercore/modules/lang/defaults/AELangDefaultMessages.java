    private final AELangModule langModule;

    public AELangDefaultMessages(AELangModule langModule) {
        this.langModule = Objects.requireNonNull(langModule, "langModule");
    }

    @Override
    public void install() throws SQLException {
        for (Map.Entry<String, String> message : MESSAGES.entrySet()) {
            langModule.installDefaultMessage(AEDefaultLanguage.CODE, message.getKey(), message.getValue());
        }
    }
